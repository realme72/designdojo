"""Contract -> Java sources (package `contract`) and the `solution.Solution` stub."""

from __future__ import annotations

from ..contract import Contract, Method, snake_to_camel

HEADER = "// GENERATED by DesignDojo from contract.yaml. Do not edit; it is regenerated on every run.\n"
BOXED = {"int": "Integer", "long": "Long", "bool": "Boolean", "str": "String"}
PRIM = {"int": "int", "long": "long", "bool": "boolean", "str": "String", "void": "void"}


def jtype(t: dict, boxed: bool = False) -> str:
    k = t["kind"]
    if k in PRIM:
        return (BOXED if boxed and k in BOXED else PRIM)[k]
    if k == "list":
        return f"List<{jtype(t['of'], True)}>"
    if k == "map":
        return f"Map<{jtype(t['key'], True)}, {jtype(t['value'], True)}>"
    return t["name"]


def _javadoc(text: str, indent: str = "", throws: list[str] | None = None) -> str:
    lines = [l for l in text.splitlines()] if text else []
    for e in throws or []:
        lines.append(f"@throws {e}")
    if not lines:
        return ""
    body = "\n".join(f"{indent} * {l}".rstrip() for l in lines)
    return f"{indent}/**\n{body}\n{indent} */\n"


def _signature(m: Method) -> str:
    params = ", ".join(f"{jtype(p.type)} {snake_to_camel(p.name)}" for p in m.params)
    return f"{jtype(m.returns)} {snake_to_camel(m.name)}({params})"


def _iface(name: str, methods: dict[str, Method], doc: str) -> str:
    out = [HEADER, "package contract;\n\n", "import java.util.List;\nimport java.util.Map;\n\n"]
    out.append(_javadoc(doc))
    out.append(f"public interface {name} {{\n")
    for m in methods.values():
        out.append(_javadoc(m.doc, "    ", m.raises))
        out.append(f"    {_signature(m)};\n\n")
    out[-1] = out[-1].rstrip("\n") + "\n"
    out.append("}\n")
    return "".join(out)


def generate_contract(c: Contract) -> dict[str, str]:
    """Return {relative path: source} for the contract package."""
    files: dict[str, str] = {}
    for name, values in c.enums.items():
        files[f"contract/{name}.java"] = (
            f"{HEADER}package contract;\n\n{_javadoc(c.docs.get(name, ''))}"
            f"public enum {name} {{ {', '.join(values)} }}\n"
        )
    for name, fields in c.dtos.items():
        comps = ", ".join(f"{jtype(f.type)} {snake_to_camel(f.name)}" for f in fields)
        copies = []
        for f in fields:
            n = snake_to_camel(f.name)
            if f.type["kind"] == "list":
                copies.append(f"        {n} = List.copyOf({n});")
            elif f.type["kind"] == "map":
                copies.append(f"        {n} = Map.copyOf({n});")
        body = (" {\n    public " + name + " {\n" + "\n".join(copies) + "\n    }\n}\n") if copies else " {}\n"
        files[f"contract/{name}.java"] = (
            f"{HEADER}package contract;\n\nimport java.util.List;\nimport java.util.Map;\n\n"
            f"{_javadoc(c.docs.get(name, ''))}public record {name}({comps}){body}"
        )
    for name, methods in {**c.provided, **c.interfaces}.items():
        files[f"contract/{name}.java"] = _iface(name, methods, c.docs.get(name, ""))
    for name in c.errors:
        files[f"contract/{name}.java"] = (
            f"{HEADER}package contract;\n\n{_javadoc(c.docs.get(name, ''))}"
            f"public class {name} extends RuntimeException {{\n"
            f"    public {name}() {{ super(); }}\n"
            f"    public {name}(String message) {{ super(message); }}\n"
            f"}}\n"
        )
    return files


def generate_stub(c: Contract) -> dict[str, str]:
    ep = c.entrypoint
    return {
        "solution/Solution.java": (
            "package solution;\n\n"
            "import contract.*;\n\n"
            "/**\n"
            " * Entry point the judge calls. Build and return your system here;\n"
            " * design everything else (classes, packages under solution/) however you like.\n"
            " */\n"
            "public final class Solution {\n"
            "    private Solution() {}\n\n"
            f"    public static {_signature(ep)} {{\n"
            '        throw new UnsupportedOperationException("TODO: implement");\n'
            "    }\n"
            "}\n"
        )
    }
