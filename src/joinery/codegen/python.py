"""Contract -> Python module (package `contract`) and the `solution` stub."""

from __future__ import annotations

from ..contract import Contract, Method

HEADER = "# GENERATED by joinery from contract.yaml. Do not edit; it is regenerated on every run.\n"
PRIM = {"int": "int", "long": "int", "bool": "bool", "str": "str", "void": "None"}


def ptype(t: dict) -> str:
    k = t["kind"]
    if k in PRIM:
        return PRIM[k]
    if k == "list":
        return f"list[{ptype(t['of'])}]"
    if k == "map":
        return f"dict[{ptype(t['key'])}, {ptype(t['value'])}]"
    return t["name"]


def _doc(text: str, indent: str, raises: list[str] | None = None) -> str:
    lines = text.splitlines() if text else []
    if raises:
        if lines:
            lines.append("")
        lines.append("Raises: " + ", ".join(raises))
    if not lines:
        return ""
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""\n'
    body = "\n".join(f"{indent}{l}".rstrip() for l in lines)
    return f'{indent}"""\n{body}\n{indent}"""\n'


def _signature(m: Method, self_: bool = True) -> str:
    params = (["self"] if self_ else []) + [f"{p.name}: {ptype(p.type)}" for p in m.params]
    return f"def {m.name}({', '.join(params)}) -> {ptype(m.returns)}:"


def generate_contract(c: Contract) -> dict[str, str]:
    out = [
        HEADER,
        "from __future__ import annotations\n\n",
        "from abc import ABC, abstractmethod\n",
        "from dataclasses import dataclass\n",
        "from enum import Enum\n\n",
    ]
    for name in c.errors:
        out.append(f"\nclass {name}(Exception):\n")
        out.append(_doc(c.docs.get(name, ""), "    ") or "    pass\n")
        out.append("\n")
    for name, values in c.enums.items():
        out.append(f"\nclass {name}(Enum):\n")
        out.append(_doc(c.docs.get(name, ""), "    "))
        out.extend(f'    {v} = "{v}"\n' for v in values)
        out.append("\n")
    for name, fields in c.dtos.items():
        out.append(f"\n@dataclass(frozen=True)\nclass {name}:\n")
        out.append(_doc(c.docs.get(name, ""), "    "))
        out.extend(f"    {f.name}: {ptype(f.type)}\n" for f in fields)
        out.append("\n")
    for name, methods in {**c.provided, **c.interfaces}.items():
        out.append(f"\nclass {name}(ABC):\n")
        out.append(_doc(c.docs.get(name, ""), "    "))
        for m in methods.values():
            out.append(f"    @abstractmethod\n    {_signature(m)}\n")
            out.append(_doc(m.doc, "        ", m.raises) or "        ...\n")
            out.append("\n")
    return {"contract/__init__.py": "".join(out).rstrip() + "\n"}


def generate_stub(c: Contract) -> dict[str, str]:
    ep = c.entrypoint
    names = sorted({p.type["name"] for p in ep.params if "name" in p.type} | {ep.returns["name"]})
    return {
        "solution/__init__.py": (
            f"from contract import {', '.join(names)}\n\n\n"
            f"{_signature(ep, self_=False)}\n"
            '    """Entry point the judge calls. Build and return your system here;\n'
            '    design everything else (modules inside solution/) however you like."""\n'
            "    raise NotImplementedError\n"
        )
    }
